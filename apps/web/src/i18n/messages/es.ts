const LOCALE = 'es-ES';
const plurals = new Intl.PluralRules(LOCALE);
const megabyteFormat = new Intl.NumberFormat(LOCALE, {
  minimumFractionDigits: 1,
  maximumFractionDigits: 1,
});

function plural(n: number, one: string, other: string): string {
  return plurals.select(n) === 'one' ? `${n} ${one}` : `${n} ${other}`;
}

function utc(date: string): Date {
  return new Date(`${date}T00:00:00Z`);
}

function dateIn(date: string, options: Intl.DateTimeFormatOptions): string {
  return utc(date).toLocaleDateString(LOCALE, { ...options, timeZone: 'UTC' });
}

