import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const check = process.argv.includes('--check');
const root = new URL('../', import.meta.url);
const result = await build({
  configFile: false,
  root: fileURLToPath(root),
  logLevel: 'warn',
  build: {
    lib: { entry: 'client/main.ts', name: 'MetrackSite', formats: ['iife'] },
    target: 'es2017',
    minify: false,
    write: false,
    rolldownOptions: { output: { strict: true } },
  },
});
const [bundle] = Array.isArray(result) && result.length === 1 ? result : [];
const chunk = bundle?.output[0];
if (
  bundle?.output.length !== 1 ||
  chunk?.type !== 'chunk' ||
  chunk.imports.length !== 0 ||
  chunk.dynamicImports.length !== 0
) {
  throw new Error('The public pages client must bundle into one script without imports.');
}

const assets = [
  [
    'SITE_JS',
    'The one script of the public pages: the profile backdrop, the library filters, the statistics year and the collage.',
    chunk.code,
  ],
  [
    'SITE_CSS',
    'The stylesheet of the public pages, without the rating colours `siteStylesheet` adds.',
    await readFile(new URL('client/site.css', root), 'utf8'),
  ],
].map(([name, description, source]) => {
  if (source.includes('`') || source.includes('${') || source.endsWith('\\')) {
    throw new Error(`${name} cannot be embedded verbatim in a String.raw template.`);
  }
  return {
    name,
    file: new URL(`src/assets/${name}.ts`, root),
    content: `/** ${description} Generated by build:assets. */\nexport const ${name} = String.raw\`${source}\`;\n`,
  };
});

for (const { name, file, content } of assets) {
  if (check) {
    const current = await readFile(file, 'utf8').catch((error) => {
      if (error.code === 'ENOENT') return '';
      throw error;
    });
    if (current !== content) {
      console.error(`${name}.ts is out of date. Run npm run build:assets -w @metrack/site.`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(file, content);
  }
}
